/**
 * Cookie and header names shared by the API (which sets and checks them) and the web app
 * (whose admin middleware reads the access cookie and whose client echoes the CSRF token).
 */
export const AUTH_COOKIES = {
  /** httpOnly JWT access token, sent to every path. */
  ACCESS_TOKEN: 'codex_at',
  /** httpOnly opaque refresh token, scoped to the auth routes. */
  REFRESH_TOKEN: 'codex_rt',
  /** Readable CSRF token; the client copies it into `CSRF_HEADER`. */
  CSRF_TOKEN: 'codex_csrf',
} as const;

/** Header carrying the double-submit CSRF token on state-changing requests. */
export const CSRF_HEADER = 'x-csrf-token';

/**
 * Header the Next.js server sends with the server-only `INTERNAL_API_TOKEN` on its own fetches
 * (SSR/ISR), so its traffic gets its own rate limit instead of the per-IP one. Browsers never
 * send it: CORS does not allow it.
 */
export const INTERNAL_API_HEADER = 'x-codex-internal';

/** Header carrying the request id (generated by the API when absent or malformed). */
export const REQUEST_ID_HEADER = 'x-request-id';

export const AUTH_TOKEN_TTL = {
  ACCESS_SECONDS: 15 * 60,
  /** Sliding: every refresh issues a token valid for another 7 days… */
  REFRESH_SECONDS: 7 * 24 * 60 * 60,
  /** …but a login session (token family) never lives longer than 30 days. */
  SESSION_MAX_SECONDS: 30 * 24 * 60 * 60,
} as const;
